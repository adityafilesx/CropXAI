"""Reproducible scan for mock/placeholder/random-valued code. Writes docs/revision/LEGACY_PLACEHOLDER_SCAN.md."""
import re, sys
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
MARK=re.compile(r'\b(mock(ed|ing)?|dummy|placeholder|for demonstration)\b',re.I)
RAND=re.compile(r'np\.random\.(rand|uniform|normal|randint|random|choice)\b|torch\.rand(n)?\(')
ACTIVE=['src/cropxai','src/cropxai_analysis','scripts']
LEGACY=['src/research','src/models','src/xai','src/uncertainty','src/core','src/cli','src/data','src/utils','src/deployment','src/experiments']

TEXT_SCRIPTS={Path(__file__).name,'build_manuscript.py','validate_manuscript.py'}  # scripts that contain prose describing the legacy mocks

def scan(dirs, vendor_skip=True):
    rows=[]
    for d in dirs:
        for p in sorted((ROOT/d).rglob('*.py')):
            if '__pycache__' in p.parts or (vendor_skip and 'vendor' in p.parts) or p.name in TEXT_SCRIPTS: continue
            for i,line in enumerate(p.read_text(errors='ignore').splitlines(),1):
                m=MARK.search(line); r=RAND.search(line)
                if m or r: rows.append((str(p.relative_to(ROOT)),i,'marker' if m else 'random',line.strip()[:140]))
    return rows

def main():
    active=scan(ACTIVE); legacy=scan(LEGACY)
    bad=[a for a in active if a[2]=='marker' or re.search(r'np\.random\.',a[3])]
    L=['# Scan for mock / placeholder / random-valued code','',
       'Generated by `scripts/scan_legacy_placeholders.py` (patterns: mock/dummy/placeholder/"for demonstration" markers; `np.random.*`, `torch.rand*` calls).','',
       '## Active pipeline (`src/cropxai`, `src/cropxai_analysis`, `scripts`)','',
       f'* Marker words or unseeded NumPy global RNG: **{len(bad)}** (expected 0; enforced by `tests/test_revision_v2.py::FallbackEliminationTests::test_active_path_has_no_mock_markers`).',
       '* Remaining RNG use is seeded (`torch.Generator().manual_seed`, `default_rng(seed)`) for batch order, flips, random-deletion control and synthetic noise:','']
    L+=[f'  * `{f}:{n}` `{t}`' for f,n,k,t in active if k=='random']
    L+=['','## Legacy tree (not used by the revised pipeline; preserved for audit)','',f'{len(legacy)} lines match. Files whose own comments call the code a mock/demonstration or that draw metric values from a random generator:','','| File:line | Kind | Line |','|---|---|---|']
    L+=[f"| `{f}:{n}` | {k} | `{t.replace('|','/')}` |" for f,n,k,t in legacy if k=='marker' or 'benchmarking' in f]
    L+=['','**Reading.** Legacy modules named for Nemenyi post-hoc tests, Bayesian ranking, statistical power, ANOVA stability, publication figures/tables and the XAI benchmark manager are documented in their own comments as mocks; the XAI benchmark manager assigns `deletion_auc` and `insertion_auc` from `np.random.uniform`. The scan cannot show which of these produced numbers in the submitted manuscript, but none of their outputs is reused here, and the statistical claims they implemented (Nemenyi significance, Bayesian ranking, power) are withdrawn in the revised paper.','']
    (ROOT/'docs/revision/LEGACY_PLACEHOLDER_SCAN.md').write_text('\n'.join(L)); print('active violations:',len(bad),'legacy matches:',len(legacy)); return 1 if bad else 0
if __name__=='__main__': raise SystemExit(main())
