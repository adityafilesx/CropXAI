"""
CropXAI Cluster Deployment CLI
================================
Generates optimal SLURM array batch scripts to execute the massive experiment
grid across an HPC cluster in parallel.
"""

from __future__ import annotations

import argparse
import logging
from pathlib import Path

logger = logging.getLogger(__name__)


def setup_parser(subparsers: argparse._SubParsersAction) -> None:
    parser = subparsers.add_parser("cluster", help="Manage HPC cluster deployments")
    cluster_subparsers = parser.add_subparsers(dest="cluster_cmd", required=True)
    
    gen_parser = cluster_subparsers.add_parser("generate-slurm", help="Generate SLURM batch scripts for the massive grid")
    gen_parser.add_argument("--output-dir", default="cluster_scripts", help="Output directory for SLURM scripts")


def handle_command(args: argparse.Namespace) -> None:
    if args.cluster_cmd == "generate-slurm":
        _handle_generate_slurm(args)


def _handle_generate_slurm(args: argparse.Namespace) -> None:
    out_dir = Path(args.output_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    
    logger.info("=" * 60)
    logger.info("CropXAI SLURM Batch Generator")
    logger.info("=" * 60)
    
    # The full massive grid
    models = [
        "ResNet-18", "ResNet-50", "EfficientNet-B0", "ConvNeXt-T", 
        "ViT-Base", "Swin-T", "SegFormer-B0",
        "Prithvi-100M", "SatMAE", "DOFA", "ScaleMAE"
    ]
    datasets = ["eurosat", "bigearthnet", "pastis", "cropharvest"]
    seeds = [42, 100, 999, 1234, 5678]  # 5 seeds for statistical robustness
    epochs = 100
    
    script_path = out_dir / "submit_master_campaign.sh"
    
    # We use a SLURM job array for extreme parallelism.
    # We will generate a parameter mapping file and a SLURM script that indexes into it.
    
    param_file = out_dir / "campaign_params.txt"
    param_lines = []
    
    for m in models:
        for d in datasets:
            for s in seeds:
                param_lines.append(f"--model {m} --dataset {d} --seed {s} --epochs {epochs}")
                
    param_file.write_text("\n".join(param_lines))
    num_jobs = len(param_lines)
    
    logger.info(f"Generated massive grid configuration: {num_jobs} distinct permutations.")
    
    slurm_script = f"""#!/bin/bash
#SBATCH --job-name=cropxai_campaign
#SBATCH --output=logs/cropxai_%A_%a.out
#SBATCH --error=logs/cropxai_%A_%a.err
#SBATCH --array=1-{num_jobs}
#SBATCH --time=12:00:00
#SBATCH --partition=gpu
#SBATCH --gres=gpu:1
#SBATCH --cpus-per-task=4
#SBATCH --mem=32G

# ----------------------------------------------------------------------------
# CropXAI Massive Scientific Discovery Campaign
# Automatically generated by `cropxai cluster generate-slurm`
# ----------------------------------------------------------------------------

# Ensure log directory exists
mkdir -p logs

# Load modules (Adjust for your specific HPC environment)
# module load CUDA/12.1
# module load python/3.11

# Activate virtual environment
source venv/bin/activate

# Read the specific parameters for this array task
PARAMS=$(sed -n "${{SLURM_ARRAY_TASK_ID}}p" {param_file.name})

echo "Running task ID $SLURM_ARRAY_TASK_ID with params: $PARAMS"

# Execute the isolated shard
PYTHONPATH=. ./cropxai campaign run $PARAMS

echo "Task completed."
"""
    script_path.write_text(slurm_script)
    
    logger.info(f"Created parameter map: {param_file}")
    logger.info(f"Created SLURM submission script: {script_path}")
    logger.info("")
    logger.info("To deploy to your cluster, run:")
    logger.info(f"  sbatch {script_path}")
    logger.info("=" * 60)

__all__ = ["setup_parser", "handle_command"]
