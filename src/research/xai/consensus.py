"""
Explainability Consensus Engine
===============================
Compares multiple XAI methods (GradCAM, IG, SHAP, etc.) to compute 
agreement, faithfulness, and stability across models.
"""

import logging
from typing import List, Dict
import numpy as np

logger = logging.getLogger(__name__)

class XAIConsensusEngine:
    def __init__(self, methods: List[str] = ['gradcam', 'ig', 'shap']):
        self.methods = methods
        
    def compute_agreement(self, heatmaps: Dict[str, np.ndarray]) -> float:
        """
        Computes the pairwise Intersection over Union (IoU) or Structural Similarity (SSIM)
        between heatmaps generated by different XAI methods for the same input.
        Returns an agreement score [0, 1].
        """
        logger.info(f"Computing XAI consensus across {len(self.methods)} methods...")
        
        scores = []
        method_names = list(heatmaps.keys())
        for i in range(len(method_names)):
            for j in range(i + 1, len(method_names)):
                h1 = heatmaps[method_names[i]]
                h2 = heatmaps[method_names[j]]
                # Flatten and compute Pearson correlation as a proxy for agreement
                corr = np.corrcoef(h1.flatten(), h2.flatten())[0, 1]
                scores.append(corr)
                
        if not scores:
            return 1.0
            
        return max(0.0, float(np.mean(scores)))
