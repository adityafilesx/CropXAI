"""
CropXAI Scientific Hypothesis Registry
========================================

Registers explicit scientific hypotheses and maps them to the evidence
generated by the ASCOPE experimental campaign.
"""

from __future__ import annotations

import logging
from typing import Any

logger = logging.getLogger(__name__)


class HypothesisRegistry:
    """Manages scientific hypotheses and their validation status."""

    def __init__(self) -> None:
        self.hypotheses: dict[str, dict[str, Any]] = {}

    def register_hypothesis(self, hyp_id: str, statement: str) -> None:
        """Registers a new hypothesis to be tested."""
        self.hypotheses[hyp_id] = {
            "statement": statement,
            "evidence": [],
            "status": "UNTESTED"
        }
        logger.info("Registered Hypothesis [%s]: %s", hyp_id, statement)

    def attach_evidence(self, hyp_id: str, evidence_id: str, supported: bool) -> None:
        """Attaches an evidence block to a hypothesis."""
        if hyp_id not in self.hypotheses:
            raise ValueError(f"Hypothesis {hyp_id} not found.")
            
        self.hypotheses[hyp_id]["evidence"].append({
            "evidence_id": evidence_id,
            "supported": supported
        })
        
        # Evaluate status based on all evidence
        all_supported = all(e["supported"] for e in self.hypotheses[hyp_id]["evidence"])
        self.hypotheses[hyp_id]["status"] = "SUPPORTED" if all_supported else "REJECTED"

    def get_summary(self) -> dict[str, Any]:
        return self.hypotheses


__all__ = ["HypothesisRegistry"]
